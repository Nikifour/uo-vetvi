/**
 * Обновить сценарий в мире из компендиума, не тронув пройденное.
 *
 * Зачем. Перетаскивание из пакета всегда создаёт **новую копию**, а не
 * обновляет старую. Значит «поправил сценарий в markdown — пересобрал —
 * перетащил снова» даёт второй журнал с чистым ходом, а прогресс кампании
 * остаётся в первом, вместе с устаревшими стрелками. Выбирать между свежей
 * схемой и накопленным ходом ведущему не должно приходиться.
 *
 * Поэтому здесь другое: берём тот же журнал в мире и переносим в него
 * схему и текст из источника. Флаг `ход` не трогаем вовсе — он и есть
 * то, ради чего всё это затеяно.
 *
 * Держится на том, что **id страниц при импорте сохраняются**: Foundry
 * чистит только корневой `_id`, а вложенным оставляет свои
 * (`keepEmbeddedIds` по умолчанию true). Поэтому страницы мира и пакета
 * сопоставляются по id, а не по имени, — переименование узла не рвёт связь.
 */

import { MODULE_ID } from "./svod.mjs";
import { Т } from "./yazyk.mjs";

/** Откуда журнал приехал. Foundry пишет это сам при импорте из пакета. */
export const источник = журнал => журнал?._stats?.compendiumSource ?? null;

/**
 * Найти источник, если Foundry его не записал.
 *
 * Бывает у журналов, перенесённых давно или собранных руками. Ищем по имени
 * среди журнальных пакетов — и обязательно спрашиваем, тот ли это журнал:
 * тёзка из чужого модуля перезаписал бы сценарий чужой схемой.
 */
export async function поискатьИсточник(журнал) {
  const имя = журнал.name;
  const находки = [];

  for (const пак of game.packs) {
    if (пак.documentName !== "JournalEntry") continue;
    const индекс = await пак.getIndex();
    for (const з of индекс) if (з.name === имя) находки.push(`${пак.collection}.${з._id}`);
  }
  return находки;
}

/**
 * Перенести схему и текст из источника в журнал мира.
 *
 * @returns {Promise<{обновлено: number, создано: number, лишние: string[]}|null>}
 */
export async function обновитьИзИсточника(журнал, uuid, { текст = true, убиратьЛишние = false } = {}) {
  if (!game.user.isGM) return null;

  const из = await fromUuid(uuid);
  if (!из) {
    ui.notifications.error(Т("Источник не найден — пакет отключён или журнал из него удалён."));
    return null;
  }

  const источниковы = new Map(из.pages.contents.map(с => [с.id, с]));
  const мировы = new Map(журнал.pages.contents.map(с => [с.id, с]));

  const правки = [];
  for (const [id, с] of источниковы) {
    const своя = мировы.get(id);
    if (!своя) continue;
    const правка = { _id: id, name: с.name, sort: с.sort };
    // Флаг узла кладём целиком: узел мог перестать быть узлом, и тогда
    // старый флаг обязан уйти, иначе страница останется на холсте призраком.
    правка[`flags.${MODULE_ID}.узел`] = с.getFlag(MODULE_ID, "узел") ?? null;
    if (текст) правка["text.content"] = с.text?.content ?? "";
    правки.push(правка);
  }

  const новые = [...источниковы.values()]
    .filter(с => !мировы.has(с.id))
    .map(с => {
      const д = с.toObject();
      delete д._stats;
      return д;
    });

  const лишние = [...мировы.values()].filter(с => !источниковы.has(с.id));

  if (правки.length) await журнал.updateEmbeddedDocuments("JournalEntryPage", правки);
  // keepId обязателен: рёбра сценария ссылаются на id страниц.
  if (новые.length) await журнал.createEmbeddedDocuments("JournalEntryPage", новые, { keepId: true });
  if (убиратьЛишние && лишние.length) {
    await журнал.deleteEmbeddedDocuments("JournalEntryPage", лишние.map(с => с.id));
  }

  // Схема — целиком из источника. Ход остаётся какой был: он в другом флаге,
  // и сборка его не пишет вовсе.
  const схема = из.getFlag(MODULE_ID, "сценарий");
  if (схема) await журнал.setFlag(MODULE_ID, "сценарий", схема);

  return {
    обновлено: правки.length,
    создано: новые.length,
    лишние: (убиратьЛишние ? [] : лишние).map(с => с.name),
  };
}

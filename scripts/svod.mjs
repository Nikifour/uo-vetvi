/* ─────────────────────────── ход кампании ─────────────────────────── */

/**
 * Метки, вытекающие из пройденного.
 *
 * Считаются заново от всего пройденного, а не накапливаются. Раньше метки
 * только ставились: снял отметку — метка оставалась поднятой, и ведущему
 * приходилось гасить её руками, помня, какая от какого узла. Пересчёт
 * избавляет от этой памяти: метка есть ровно тогда, когда её ставит
 * какой-нибудь пройденный узел и никто более поздний не снимает.
 *
 * Порядок берётся из `пройдено` — это список в порядке отметок, поэтому
 * поздний узел перебивает раннего, как оно и было за столом.
 *
 * Частично пройденные узлы метки НЕ поднимают. В этом весь их смысл: книгу
 * нашли, но не прочли — событие началось, последствий ещё нет.
 *
 * Метки, которых не касается ни один пройденный узел, остаются как были:
 * их ведущий поднял руками, и пересчёт не вправе их трогать.
 */
function поднятыеОтПройденного(журнал, пройдено, прежние = []) {
  /*
   * Управляемая метка — та, которую упоминает хоть один узел схемы, а не только
   * пройденный. Иначе снятие отметки ничего бы не меняло: узел ушёл из
   * пройденного, «управлять» стало некому, и старое значение сохранялось бы
   * как ручное. Именно на этом всё и ломалось.
   */
  const управляемые = new Set();
  for (const страница of журнал.pages) {
    const у = страница.getFlag(MODULE_ID, "узел");
    if (!у) continue;
    for (const м of у.ставит ?? []) управляемые.add(м);
    for (const м of у.снимает ?? []) управляемые.add(м);
  }

  const метки = {};
  for (const id of пройдено) {
    const у = журнал.pages.get(id)?.getFlag(MODULE_ID, "узел");
    if (!у) continue;
    for (const м of у.ставит ?? []) метки[м] = true;
    for (const м of у.снимает ?? []) метки[м] = false;
  }

  // Метки, к которым не привязан ни один узел, ведущий держит руками — их не трогаем.
  for (const м of прежние) {
    if (!управляемые.has(м)) метки[м] = true;
  }
  return Object.entries(метки).filter(([, стоит]) => стоит).map(([м]) => м);
}

/** Три состояния узла: не случилось, случилось частично, случилось. */
export const КАК = { нет: "нет", частично: "частично", полностью: "полностью" };

export function какОтмечен(свод, узелId) {
  if ((свод.ход?.пройдено ?? []).includes(узелId)) return КАК.полностью;
  if ((свод.ход?.частично ?? []).includes(узелId)) return КАК.частично;
  return КАК.нет;
}

/**
 * Отметить узел: случился целиком, случился частично или не случился вовсе.
 *
 * Частичное нужно там, где шаг растянут во времени: книгу нашли, но не
 * прочитали. Заводить на каждый такой шаг отдельный узел — раздувать схему
 * на ровном месте, а врать «случилось» нельзя: метки поднимутся раньше срока.
 */
export async function отметить(журнал, узелId, как = КАК.полностью, партияId = null) {
  if (!game.user.isGM) return;
  if (!журнал.pages.get(узелId)) return;

  return правитьХод(журнал, х => {
    const пройдено = (х.пройдено ?? []).filter(id => id !== узелId);
    const частично = (х.частично ?? []).filter(id => id !== узелId);

    if (как === КАК.полностью) пройдено.push(узелId);
    if (как === КАК.частично) частично.push(узелId);

    return {
      ...х,
      пройдено,
      частично,
      поднятые: поднятыеОтПройденного(журнал, пройдено, х.поднятые ?? []),
    };
  }, партияId);
}

export const снятьОтметку = (журнал, узелId, партияId = null) =>
  отметить(журнал, узелId, КАК.нет, партияId);


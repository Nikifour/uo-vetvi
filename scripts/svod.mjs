/**
 * Сценарий поверх журнала.
 *
 * Сценарий — обычный журнал Foundry, узел — его страница. Так и задумано:
 * текст узла пишется штатным редактором, ссылки на сцены, актёров и предметы
 * работают сами, права раздаются как всегда, а готовый сценарий кладётся
 * в компендиум и уезжает другому ведущему целиком — вместе с прозой.
 *
 * Модуль добавляет к этому только связи. В флаге журнала лежат стрелки, метки
 * и ход кампании; в флаге страницы — вид узла, место на холсте и какие метки
 * узел ставит. Уберёте модуль — останется журнал со страницами, а не мусор.
 *
 * ## Один сценарий, несколько партий
 *
 * Схема общая, а ход у каждой партии свой. Ведущий, водящий в одном мире две
 * компании, пишет один сценарий: новый узел, стрелка, метка появляются сразу
 * у всех. Но пройденное, поднятые метки и замечания принадлежат партии — они
 * и есть то, чем партии друг от друга отличаются.
 *
 * Отсюда раскладка по флагам журнала:
 *
 * - `сценарий` — что написано: узлы, стрелки, метки, ветки, начало. Одно
 *   на всех, приезжает из сборки.
 * - `партии` — список компаний: имя, цвет, заметка о составе.
 * - `ходы` — по записи на партию: пройдено, частично, замечания, метки.
 * - `текущая` — какую партию сейчас ведут.
 *
 * `текущая` лежит в журнале, а не в настройке браузера, нарочно. Настройка
 * браузера живёт на одной машине: сел за другой — и отмечаешь ход не той
 * партии, ничего об этом не зная. Ошибка тихая и дорогая, а выигрыш
 * (два ведущих смотрят разные партии разом) нужен куда реже.
 *
 * ## Почему всё хранится списками
 *
 * Foundry сливает объекты при записи: если во флаге лежит `{узелId: текст}`
 * и записать его без удалённого ключа, ключ вернётся — слияние его сохранит.
 * Списки же заменяются целиком. Поэтому замечания, поднятые метки и сами
 * партии хранятся списками, а привычный вид «ключ — значение» собирается
 * в `свести()` для тех, кто читает. Раньше на этом молча ломалось стирание
 * замечания: текст убирали, а он оставался.
 */

import { Т, М } from "./yazyk.mjs";

export const MODULE_ID = "uo-vetvi";

/*
 * Виды узла. `класс` — латиницей для стилей: кириллица в имени CSS-класса
 * законна, но стили писались латиницей, и прежде `uo-vid-развилка` молча
 * не находил своего `uo-vid-razvilka` — пунктир развилки не рисовался.
 *
 * Запас — узел, который ведущий тратит по обстановке, без дороги к нему
 * (правила — в pravila.mjs, «Запас»).
 */
export const ВИДЫ = {
  сцена: { имя: М("Сцена"), знак: "◆", класс: "scena" },
  развилка: { имя: М("Развилка"), знак: "◇", класс: "razvilka" },
  финал: { имя: М("Финал"), знак: "★", класс: "final" },
  запас: { имя: М("Запас"), знак: "✚", класс: "zapas" },
};

const пусто = () => ({ версия: 1, рёбра: [], метки: [], группы: [], начало: null });

/** Чистый ход: партия только села за стол. */
const пустойХод = партия => ({ партия, пройдено: [], частично: [], заметки: [], поднятые: [] });

/**
 * Цвета групп. Не радуга: холст должен читаться, а не рябить.
 * Первый — «без группы», он же цвет узла по умолчанию.
 */
export const ЦВЕТА = ["#6b6b73", "#7fa3cc", "#6fae5a", "#c9a227", "#b4553f", "#a982d1", "#3fa9a0"];

/* ─────────────────────────── чтение ─────────────────────────── */

/** Все журналы мира, которые объявлены сценариями. */
export const сценарии = () =>
  game.journal.filter(ж => ж.getFlag(MODULE_ID, "сценарий"));

export const этоСценарий = журнал => !!журнал?.getFlag(MODULE_ID, "сценарий");

/* ─────────────────────────── партии ─────────────────────────── */

/**
 * Компании, которые водят по этому сценарию.
 *
 * Пустой список — не беда, а «партий ещё не заводили»: сценарий, приехавший
 * из компендиума, или мир, который водили до появления этой возможности.
 * Тогда ход читается из прежнего одиночного флага, а первая партия
 * заводится при первом же открытии графа (см. `обеспечитьПартию`).
 */
export function партии(журнал) {
  const список = журнал?.getFlag(MODULE_ID, "партии");
  if (!Array.isArray(список)) return [];
  return список.filter(п => п?.id).map((п, i) => ({
    id: п.id,
    имя: п.имя || Т("Партия"),
    цвет: п.цвет || ЦВЕТА[(i % (ЦВЕТА.length - 1)) + 1],
    заметка: п.заметка ?? "",
  }));
}

export const партия = (журнал, id) => партии(журнал).find(п => п.id === id) ?? null;

/**
 * Какую партию сейчас ведут.
 *
 * Записанная могла быть удалена — тогда берём первую, а не пустоту: граф
 * без партии показывал бы чистый ход, и ведущий решил бы, что потерял
 * прогресс.
 */
export function текущаяПартия(журнал) {
  const все = партии(журнал);
  if (!все.length) return null;
  const id = журнал.getFlag(MODULE_ID, "текущая");
  return все.find(п => п.id === id) ?? все[0];
}

/** Ход одной партии, как он лежит в журнале. */
function ходПартии(журнал, партияId) {
  const ходы = журнал?.getFlag(MODULE_ID, "ходы");
  const свой = Array.isArray(ходы) ? ходы.find(х => х.партия === партияId) : null;
  return свой ?? пустойХод(партияId);
}

/**
 * Где стоят все партии — для взгляда со стороны.
 *
 * Ради этого и затевалось: на одном холсте видно, что первая компания уже
 * взяла финал, а вторая до него и не дошла. Полного свода тут не нужно,
 * поэтому берётся только пройденное.
 */
export function ходыПартий(журнал) {
  return партии(журнал).map(п => {
    const х = ходПартии(журнал, п.id);
    return { ...п, пройдено: х.пройдено ?? [], частично: х.частично ?? [] };
  });
}

/**
 * Прежний одиночный ход — до разделения по партиям.
 *
 * Читается только пока партий нет: сразу после переезда флаг убирается,
 * и эта дорожка больше не используется.
 */
function прежнийХод(журнал) {
  const х = журнал?.getFlag(MODULE_ID, "ход");
  if (!х) return пустойХод(null);
  return {
    партия: null,
    пройдено: х.пройдено ?? [],
    частично: х.частично ?? [],
    заметки: Object.entries(х.заметки ?? {}).map(([узел, текст]) => ({ узел, текст })),
    поднятые: Object.entries(х.метки ?? {}).filter(([, в]) => в).map(([м]) => м),
  };
}

/**
 * Свести журнал к плоской сводке, с которой работают правила.
 *
 * Правила ничего не знают о журналах — им дают узлы, стрелки и метки списком.
 * Здесь же чинится и мелочь вроде пропавших полей: сценарий мог приехать
 * из другого мира или пережить правку руками.
 */
export function свести(журнал, партияId = undefined) {
  const сценарий = журнал?.getFlag(MODULE_ID, "сценарий") ?? пусто();

  const всеПартии = партии(журнал);
  const своя = всеПартии.length
    ? (всеПартии.find(п => п.id === партияId) ?? текущаяПартия(журнал))
    : null;
  const ход = своя ? ходПартии(журнал, своя.id) : прежнийХод(журнал);

  /*
   * Узел — страница с флагом «узел». Прочие страницы журнала это просто текст:
   * вступление сценария, заметка на полях, приложение. Раньше узлом считалась
   * любая страница, и стоило сценарию приехать из сборки — вступление
   * становилось узлом-сиротой, до которого «нет дороги от начала».
   *
   * Оговорка на случай беды: если флага нет **ни у одной** страницы, схема
   * пришла покалеченной — правкой руками, переносом из чужого мира. Тогда
   * узлами считаются все страницы, как прежде: лучше схема с лишними узлами,
   * чем пустой холст вместо сценария.
   */
  const все = журнал?.pages?.contents ?? [];
  const сФлагом = все.filter(с => с.getFlag(MODULE_ID, "узел"));
  const страницы = сФлагом.length ? сФлагом : все;

  const узлы = страницы.map(с => {
    const у = с.getFlag(MODULE_ID, "узел") ?? {};
    return {
      id: с.id,
      имя: с.name,
      вид: у.вид in ВИДЫ ? у.вид : "сцена",
      x: Number(у.x) || 0,
      y: Number(у.y) || 0,
      ставит: у.ставит ?? [],
      снимает: у.снимает ?? [],
      группа: у.группа ?? null,
      естьМесто: Number.isFinite(у.x) && Number.isFinite(у.y),
    };
  });

  return {
    журнал,
    id: журнал?.id ?? null,
    имя: журнал?.name ?? "",
    начало: сценарий.начало ?? null,
    метки: сценарий.метки ?? [],
    группы: сценарий.группы ?? [],
    рёбра: (сценарий.рёбра ?? []).map(р => ({ подпись: "", нужны: [], запрещены: [], ...р })),
    узлы,
    партии: всеПартии,
    партия: своя,
    /*
     * Ход отдаётся в привычном виде «ключ — значение»: правила и холст читают
     * `ход.метки[id]` и `ход.заметки[id]`, и переучивать их из-за того, что
     * на диске лежат списки, незачем. Собирается на чтении, пишется списками.
     */
    ход: {
      пройдено: ход.пройдено ?? [],
      частично: ход.частично ?? [],
      заметки: Object.fromEntries((ход.заметки ?? []).map(з => [з.узел, з.текст])),
      метки: Object.fromEntries((ход.поднятые ?? []).map(м => [м, true])),
    },
  };
}

export const узел = (свод, id) => свод.узлы.find(у => у.id === id) ?? null;
export const ребро = (свод, id) => свод.рёбра.find(р => р.id === id) ?? null;
export const метка = (свод, id) => свод.метки.find(м => м.id === id) ?? null;
export const группа = (свод, id) => свод.группы.find(г => г.id === id) ?? null;

/* ─────────────────────────── запись ─────────────────────────── */

const правитьСценарий = async (журнал, как) => {
  const было = журнал.getFlag(MODULE_ID, "сценарий") ?? пусто();
  return журнал.setFlag(MODULE_ID, "сценарий", как(foundry.utils.deepClone(было)));
};

/**
 * Все ходы списком, как они лежат в журнале.
 *
 * Список, а не объект: список Foundry при записи заменяет целиком, а объект
 * сливает — и удалённая партия или стёртое замечание возвращались бы обратно.
 */
const всеХоды = журнал => {
  const ходы = журнал.getFlag(MODULE_ID, "ходы");
  return Array.isArray(ходы) ? foundry.utils.deepClone(ходы) : [];
};

const записатьХоды = (журнал, ходы) => журнал.setFlag(MODULE_ID, "ходы", ходы);

/** Правка хода одной партии. Без партии правка бессмысленна — заводим её. */
const правитьХод = async (журнал, как, партияId = null) => {
  const своя = партияId ?? (await обеспечитьПартию(журнал))?.id;
  if (!своя) return;

  const ходы = всеХоды(журнал);
  const место = ходы.findIndex(х => х.партия === своя);
  const было = место >= 0 ? ходы[место] : пустойХод(своя);
  const стало = { ...как(было), партия: своя };

  if (место >= 0) ходы[место] = стало;
  else ходы.push(стало);
  return записатьХоды(журнал, ходы);
};

/**
 * Правка ходов всех партий разом.
 *
 * Нужна там, где из сценария исчезает то, на что ходы ссылаются: убрали узел
 * или метку — вычистить их надо у каждой партии, а не только у той, которую
 * сейчас водят. Иначе у остальных останется пройденным узел, которого нет.
 */
const правитьВсеХоды = async (журнал, как) => {
  const ходы = всеХоды(журнал).map(х => ({ ...как(х), партия: х.партия }));
  return записатьХоды(журнал, ходы);
};

/* ─────────────────────── партии: заведение и правка ─────────────────────── */

/**
 * Убедиться, что партия есть, и вернуть текущую.
 *
 * Здесь же случается переезд с прежнего устройства: сценарий, который водили
 * до разделения по партиям, имел один общий ход. Он становится ходом первой
 * партии, а прежний флаг убирается — иначе две правды о пройденном жили бы
 * рядом, и неясно было бы, какая из них настоящая.
 *
 * Зовётся при открытии графа и перед любой записью хода: сценарий приезжает
 * из компендиума без партий, и первая должна появиться сама, а не по кнопке.
 */
export async function обеспечитьПартию(журнал) {
  if (!журнал) return null;

  const есть = текущаяПартия(журнал);
  if (есть) return есть;
  if (!game.user.isGM) return null;

  const первая = { id: foundry.utils.randomID(), имя: Т("Партия"), цвет: ЦВЕТА[1], заметка: "" };
  await журнал.setFlag(MODULE_ID, "партии", [первая]);
  await журнал.setFlag(MODULE_ID, "текущая", первая.id);

  const прежний = журнал.getFlag(MODULE_ID, "ход");
  const ход = { ...прежнийХод(журнал), партия: первая.id };
  await записатьХоды(журнал, [ход]);
  if (прежний) {
    await журнал.unsetFlag(MODULE_ID, "ход");
    console.log(`${MODULE_ID} | «${журнал.name}»: прежний ход стал ходом партии «${первая.имя}»`);
  }

  return первая;
}

/**
 * Завести партию. Ход у неё чистый: новая компания начинает с начала.
 *
 * Схему она получает готовую — ту же, что у остальных. В этом весь смысл
 * разделения: узлы и стрелки пишутся один раз, а идут по ним по-разному.
 */
export async function завестиПартию(журнал, имя, { цвет = null, заметка = "", перейти = true } = {}) {
  if (!game.user.isGM || !имя?.trim()) return null;
  await обеспечитьПартию(журнал);

  const все = партии(журнал);
  const новая = {
    id: foundry.utils.randomID(),
    имя: имя.trim(),
    цвет: цвет ?? ЦВЕТА[(все.length % (ЦВЕТА.length - 1)) + 1],
    заметка: заметка.trim(),
  };

  await журнал.setFlag(MODULE_ID, "партии", [...все, новая]);
  await записатьХоды(журнал, [...всеХоды(журнал), пустойХод(новая.id)]);
  if (перейти) await перейтиКПартии(журнал, новая.id);
  return новая.id;
}

export async function правитьПартию(журнал, партияId, как = {}) {
  if (!game.user.isGM) return;
  const все = партии(журнал).map(п => п.id === партияId ? { ...п, ...как } : п);
  return журнал.setFlag(MODULE_ID, "партии", все);
}

/**
 * Убрать партию вместе с её ходом.
 *
 * Последнюю не убираем: ход должен где-то жить, а граф без партии показывал бы
 * пустоту вместо прогресса. Кому нужен чистый лист — есть «начать заново».
 */
export async function удалитьПартию(журнал, партияId) {
  if (!game.user.isGM) return false;

  const все = партии(журнал);
  if (все.length < 2 || !все.some(п => п.id === партияId)) return false;

  const осталось = все.filter(п => п.id !== партияId);
  await журнал.setFlag(MODULE_ID, "партии", осталось);
  await записатьХоды(журнал, всеХоды(журнал).filter(х => х.партия !== партияId));
  if (журнал.getFlag(MODULE_ID, "текущая") === партияId) {
    await перейтиКПартии(журнал, осталось[0].id);
  }
  return true;
}

/**
 * Перенять ход другой партии.
 *
 * Нужно, когда компания раскалывается: половина игроков уходит своим путём
 * с того же места. Переписывать десяток отметок руками — работа ни о чём.
 */
export async function размножитьПартию(журнал, партияId, имя) {
  if (!game.user.isGM || !имя?.trim()) return null;

  const источник = всеХоды(журнал).find(х => х.партия === партияId);
  const новая = await завестиПартию(журнал, имя, { перейти: false });
  if (!новая || !источник) return новая;

  await записатьХоды(журнал, всеХоды(журнал).map(х =>
    х.партия === новая ? { ...foundry.utils.deepClone(источник), партия: новая } : х));
  return новая;
}

/** Какую партию ведут теперь. */
export async function перейтиКПартии(журнал, партияId) {
  if (!game.user.isGM || !партия(журнал, партияId)) return;
  return журнал.setFlag(MODULE_ID, "текущая", партияId);
}

/* ─────────────────────── сценарий: заведение ─────────────────────── */

/** Завести новый сценарий — или объявить сценарием уже написанный журнал. */
export async function завести(имя = Т("Новый сценарий"), журнал = null) {
  if (!game.user.isGM) return null;

  const ж = журнал ?? await JournalEntry.create({ name: имя, ownership: { default: 0 } });
  if (!ж) return null;
  if (!этоСценарий(ж)) await ж.setFlag(MODULE_ID, "сценарий", пусто());
  await обеспечитьПартию(ж);
  return ж;
}

/** Перестать считать журнал сценарием. Страницы и текст остаются. */
export async function расплести(журнал) {
  if (!game.user.isGM) return;
  await журнал.unsetFlag(MODULE_ID, "сценарий");
  await журнал.unsetFlag(MODULE_ID, "ход");
  await журнал.unsetFlag(MODULE_ID, "ходы");
  await журнал.unsetFlag(MODULE_ID, "партии");
  await журнал.unsetFlag(MODULE_ID, "текущая");
}

/** Добавить узел: новая страница журнала плюс место на холсте. */
export async function добавитьУзел(журнал, { имя = Т("Новый узел"), вид = "сцена", x = 60, y = 60, текст = "" } = {}) {
  if (!game.user.isGM) return null;

  const [страница] = await журнал.createEmbeddedDocuments("JournalEntryPage", [{
    name: имя,
    type: "text",
    text: { format: 1, content: текст },
    flags: { [MODULE_ID]: { узел: { вид, x, y, ставит: [], снимает: [] } } },
  }]);

  // Первый же узел становится началом, пока начало не назначено вручную.
  const сценарий = журнал.getFlag(MODULE_ID, "сценарий") ?? пусто();
  if (!сценарий.начало) await правитьСценарий(журнал, с => ({ ...с, начало: страница.id }));

  return страница;
}

export async function правитьУзел(журнал, узелId, как = {}) {
  if (!game.user.isGM) return;
  const страница = журнал.pages.get(узелId);
  if (!страница) return;

  const правка = {};
  if (как.имя !== undefined) правка.name = как.имя;

  const узел = страница.getFlag(MODULE_ID, "узел") ?? {};
  const свежий = { ...узел };
  for (const поле of ["вид", "x", "y", "ставит", "снимает", "группа"]) {
    if (как[поле] !== undefined) свежий[поле] = как[поле];
  }
  правка.flags = { [MODULE_ID]: { узел: свежий } };

  return страница.update(правка);
}


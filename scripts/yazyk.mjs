/**
 * Язык модуля: русский в исходнике, перевод словарём.
 *
 * Устройство как у gettext: ключ — сама русская фраза, а `lang/en.json`
 * переводит её. Так в коде остаётся живой текст, а не `UOVETVI.Panel.Button.42`,
 * и непереведённое видно сразу — оно просто останется русским.
 *
 * Почему не штатные `languages` в манифесте: Foundry сливает языковые файлы
 * через `mergeObject`, а тот разворачивает ключи с точками в дерево. Фраза
 * «Сценарий сходится: начало есть, тупиков нет.» превратилась бы в шесть
 * вложенных объектов. Поэтому словарь читается сам.
 *
 * Русский — родной: для него словаря нет вовсе, и это не упущение, а замысел.
 *
 * ## Какой язык берётся
 *
 * Настройка модуля «Язык модуля» (`yazyk`, у каждого своя):
 *
 * - **как в Foundry** — Foundry по-русски, значит модуль по-русски, иначе
 *   по-английски. Английский, а не русский, при любом третьем языке нарочно:
 *   немцу или поляку английский ближе, чем русский;
 * - **русский** или **English** — принудительно. Бывает, что Foundry стоит
 *   по-английски, а модуль нужен русский, — и наоборот.
 *
 * Меняется настройка с перезагрузкой: словарь читается один раз при запуске,
 * и окна, уже нарисованные на старом языке, иначе остались бы на нём.
 */

/** Языки, для которых есть словарь. Русский не в счёт — он в исходнике. */
export const ЯЗЫКИ = ["en"];

let словарь = {};
let выбранный = "ru";

/** Настройка «Язык модуля». Подписи двуязычные: сам выбор и решает, на каком языке читать. */
function зарегистрироватьНастройку(MODULE_ID) {
  if (!game.settings?.register || game.settings.settings?.has?.(`${MODULE_ID}.yazyk`)) return;
  game.settings.register(MODULE_ID, "yazyk", {
    name: "Язык модуля / Module language",
    hint: "«Как в Foundry»: русский, если Foundry по-русски, иначе английский. / “Same as Foundry”: Russian if Foundry is in Russian, English otherwise.",
    scope: "client",
    config: true,
    type: String,
    choices: { auto: "Как в Foundry / Same as Foundry", ru: "Русский", en: "English" },
    default: "auto",
    requiresReload: true,
  });
}

/**
 * Какой язык в деле по настройке модуля и языку Foundry.
 * Настройки нет или она не прочиталась — как в Foundry.
 */
export function какойЯзык(MODULE_ID, языкFoundry = game.i18n?.lang) {
  let выбор = "auto";
  try { выбор = game.settings?.get?.(MODULE_ID, "yazyk"); } catch { /* ещё не зарегистрирована */ }
  if (выбор === "ru" || ЯЗЫКИ.includes(выбор)) return выбор;
  return языкFoundry === "ru" ? "ru" : "en";
}

/**
 * Прочитать словарь под выбранный язык. Зовётся один раз при запуске.
 * Не удалось прочитать — работаем на родном языке, а не падаем.
 */
export async function загрузитьЯзык(MODULE_ID) {
  зарегистрироватьНастройку(MODULE_ID);
  выбранный = какойЯзык(MODULE_ID);
  if (выбранный === "ru") { словарь = {}; return словарь; }

  try {
    словарь = await foundry.utils.fetchJsonWithTimeout(`modules/${MODULE_ID}/lang/${выбранный}.json`) ?? {};
  } catch (е) {
    console.warn(`${MODULE_ID} | словарь «${выбранный}» не прочитан, остаёмся на русском`, е);
    словарь = {};
  }
  return словарь;
}

/**
 * Перевести фразу. Подстановки — фигурными скобками: Т("Ход {н}", { н: 3 }).
 *
 * Нет перевода — возвращается сама фраза. Пустая строка в словаре считается
 * отсутствием перевода: это «ещё не перевели», а не «здесь пусто».
 */
export function Т(текст, данные) {
  const найдено = словарь[текст];
  const строка = (typeof найдено === "string" && найдено) ? найдено : текст;
  if (!данные) return строка;
  // Скобки ловим по буквам Юникода, а не по \w: тот считается по ASCII и
  // {имя} не увидел бы вовсе — подстановка молча не сработала бы, а в окне
  // осталась бы сама скобка.
  return строка.replace(/\{([\p{L}\p{N}_]+)\}/gu, (всё, ключ) => (данные[ключ] ?? всё));
}

/**
 * Пометить фразу для словаря, не переводя её здесь.
 *
 * Нужна там, где текст объявлен заранее, а переводится позже: названия видов
 * узлов лежат в таблице ВИДЫ, и Т(в.имя) переведёт их в нужный миг — но
 * извлекатель словаря видит только буквальные строки. М("Сцена") ему их
 * и показывает, ничего не меняя в поведении.
 */
export const М = текст => текст;

/** Какой язык сейчас в деле. Для отладки и проверок. */
export const язык = () => выбранный;

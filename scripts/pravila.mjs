/**
 * Правила сценария: развилки, метки, достижимость финалов.
 *
 * Здесь нет ни Foundry, ни журналов — только сводка сценария и рассуждения о
 * ней. Поэтому всё это гоняется стендом без запуска мира: «какие финалы ещё
 * достижимы» — утверждение, за которое модуль отвечает, и проверять его на
 * живой кампании поздно.
 *
 * Сводка (свод) выглядит так:
 *
 *   {
 *     начало: "узелId" | null,
 *     узлы:  [{ id, имя, вид: "сцена"|"развилка"|"финал"|"запас", ставит: [], снимает: [] }],
 *     рёбра: [{ id, из, в, подпись, нужны: [меткаId], запрещены: [меткаId] }],
 *     метки: [{ id, имя }],
 *     ход:   { пройдено: [узелId], метки: { меткаId: true } },
 *   }
 *
 * Про честность вывода. Метки в кампании обычно только накапливаются, и тогда
 * достижимость считается точно. Но узел может метку и снять — «барон умер»
 * отменяет «барон должен услугу». С отменами задача становится неточной, и
 * модуль считает достижимость **сверху**: узел, объявленный отрезанным, отрезан
 * наверняка, а достижимый — достижим при удачном стечении. Так и написано в
 * справке; обратное обещание было бы враньём.
 *
 * ## Запас
 *
 * Узел вида «запас» — сцена, которую ведущий держит в рукаве и тратит по
 * обстановке: спасение, которое вытащит партию из безнадёжного боя. Дороги
 * к нему нет и быть не должно — он случается не потому, что партия туда
 * пришла, а потому, что ведущий так решил. Потраченный запас отмечают
 * пройденным, и его выходы открываются, как у любого пройденного узла.
 *
 * Для честности подсчёта запас считается **доступным всегда**, пока не доказано
 * обратное: он добавляется к откуда-растёт-достижимость наравне с фронтом.
 * Это та же оценка сверху. Финал, к которому ведёт только запасное спасение,
 * отрезанным не объявляется — ведущий может его потратить в любую минуту.
 * Условия, которых схема не знает («только до знакомства с мастером»), модуль
 * не проверяет, и поэтому «достижим» здесь по-прежнему значит «при удачном
 * стечении», а «отрезан» — наверняка.
 *
 * В разборе написанного запас не сирота (к нему и не должно вести) и не тупик
 * (спасение может ничем не продолжаться). А то, что достижимо только через
 * запас, сиротой тоже не считается.
 */

/** Узел в запасе: его тратят по обстановке, дороги к нему нет. */
export const запасЛи = узел => узел?.вид === "запас";

/** Id всех узлов в запасе. */
export const запасы = свод => (свод.узлы ?? []).filter(запасЛи).map(у => у.id);

/* ─────────────────────────── условия на стрелках ─────────────────────────── */

/** Верна ли метка при нынешнем наборе. */
const стоит = (метки, id) => метки instanceof Set ? метки.has(id) : !!метки?.[id];

/**
 * Пройти по стрелке можно, если все нужные метки стоят, а запрещённых нет.
 * Пустое условие — стрелка свободна.
 */
export function проходимо(ребро, метки) {
  for (const м of ребро.нужны ?? []) if (!стоит(метки, м)) return false;
  for (const м of ребро.запрещены ?? []) if (стоит(метки, м)) return false;
  return true;
}

/** Набор меток как Set — из объекта хода или из готового Set. */
export const наборМеток = метки =>
  метки instanceof Set ? new Set(метки) : new Set(Object.entries(метки ?? {}).filter(([, в]) => в).map(([к]) => к));

/** Куда можно шагнуть из узла прямо сейчас. */
export function дальше(свод, узелId, метки = свод.ход?.метки) {
  const набор = наборМеток(метки);
  return (свод.рёбра ?? []).filter(р => р.из === узелId && открыта(свод, р, набор));
}

/* ─────────────────────────── достижимость ─────────────────────────── */

const узелПоId = (свод, id) => (свод.узлы ?? []).find(у => у.id === id);

/**
 * Откуда кампания может продолжиться: все пройденные узлы, а если не пройдено
 * ничего — начало.
 *
 * Все пройденные, а не последний: у стола редко одна нить. Партия оставила
 * зацепку в первом акте и вернулась к ней через месяц — обычный ход игры,
 * и отрезать его подсчётом было бы неправдой.
 */
export function фронт(свод) {
  const пройдено = (свод.ход?.пройдено ?? []).filter(id => узелПоId(свод, id));
  if (пройдено.length) return пройдено;
  return свод.начало && узелПоId(свод, свод.начало) ? [свод.начало] : [];
}

/**
 * Решённая развилка: по одному из её выходов уже пошли.
 *
 * Развилка — выбор, который делают один раз. Барона казнили — ветка помилования
 * закрыта навсегда, и вернуться к ней нельзя даже через сцену, которая ведёт
 * к развилке снова. Без этого правила «отрезан» не сработал бы почти никогда:
 * до любой развилки почти всегда есть обходная дорога.
 *
 * Оттого вид узла — не украшение. «Сцена» остаётся открытой, «развилка»
 * захлопывается за спиной; выбирая вид, автор говорит, к чему можно вернуться.
 */
export function решена(свод, узелId) {
  if (узелПоId(свод, узелId)?.вид !== "развилка") return false;
  const пройдено = new Set(свод.ход?.пройдено ?? []);
  if (!пройдено.has(узелId)) return false;
  return (свод.рёбра ?? []).some(р => р.из === узелId && пройдено.has(р.в));
}

/**
 * Открыта ли стрелка: и условие из меток выполнено, и развилка позади неё
 * ещё не решена в другую сторону.
 */
export function открыта(свод, ребро, метки) {
  if (!проходимо(ребро, метки)) return false;
  if (!решена(свод, ребро.из)) return true;
  return (свод.ход?.пройдено ?? []).includes(ребро.в);
}

/**
 * Что вообще достижимо: неподвижная точка по узлам и меткам разом.
 *
 * Растим два множества, пока растут: достижимый узел добавляет свои метки,
 * новая метка открывает стрелки, стрелки добавляют узлы. Снятие меток при
 * этом не учитывается — отсюда оценка сверху, о которой сказано выше.
 *
 * Узлы в запасе добавляются к «откуда» всегда: ведущий может потратить
 * их в любую минуту (см. «Запас» в начале файла).
 */
export function достижимое(свод, откуда = фронт(свод), метки = свод.ход?.метки) {
  const узлы = new Set([...откуда, ...запасы(свод)]);
  const набор = наборМеток(метки);

  let росло = true;
  while (росло) {
    росло = false;

    for (const id of узлы) {
      const узел = узелПоId(свод, id);
      for (const м of узел?.ставит ?? []) {
        if (набор.has(м)) continue;
        набор.add(м);
        росло = true;
      }
    }

    for (const р of свод.рёбра ?? []) {
      if (!узлы.has(р.из) || узлы.has(р.в)) continue;
      if (!открыта(свод, р, набор)) continue;
      узлы.add(р.в);
      росло = true;
    }
  }

  return { узлы, метки: набор };
}

/**
 * Финалы: какие ещё в игре, какие отрезаны.
 *
 * Пройденный финал считается состоявшимся — кампания пришла к нему, и это уже
 * не прогноз.
 */
export function итоги(свод) {
  const { узлы } = достижимое(свод);
  const пройдено = new Set(свод.ход?.пройдено ?? []);

  return (свод.узлы ?? [])
    .filter(у => у.вид === "финал")
    .map(у => ({
      id: у.id,
      имя: у.имя,
      состоялся: пройдено.has(у.id),
      достижим: узлы.has(у.id),
      отрезан: !узлы.has(у.id) && !пройдено.has(у.id),
    }));
}

/* ─────────────────────────── проверка сценария ─────────────────────────── */

/**
 * Что не сходится в написанном.
 *
 * Не запрет, а разбор: сценарий с висящим узлом вполне себе играется, просто
 * автор обычно хочет об этом знать. Считается от начала и без учёта хода —
 * вопрос к тексту, а не к партии.
 */
export function разбор(свод) {
  const все = свод.узлы ?? [];
  const рёбра = свод.рёбра ?? [];
  const есть = new Set(все.map(у => у.id));

  const отНачала = свод.начало
    ? достижимое({ ...свод, ход: null }, [свод.начало], new Set()).узлы
    : new Set();

  const изУзла = new Map();
  for (const р of рёбра) изУзла.set(р.из, (изУзла.get(р.из) ?? 0) + 1);
  const вУзел = new Set(рёбра.map(р => р.в));

  return {
    безНачала: !свод.начало || !есть.has(свод.начало),
    // Запас сиротой не бывает: к нему и не должно вести. Что за ним — достижимо через него.
    сироты: все.filter(у => у.id !== свод.начало && !запасЛи(у) && !отНачала.has(у.id)).map(у => у.id),
    тупики: все.filter(у => у.вид !== "финал" && !запасЛи(у) && !изУзла.get(у.id)).map(у => у.id),
    // Не ошибка, а вопрос: стрелка в запас делает его обычной сценой по смыслу.
    запасСоВходом: все.filter(у => запасЛи(у) && вУзел.has(у.id)).map(у => у.id),
    финалыСВыходом: все.filter(у => у.вид === "финал" && изУзла.get(у.id)).map(у => у.id),
    висячие: рёбра.filter(р => !есть.has(р.из) || !есть.has(р.в)).map(р => р.id),
    меткиНиоткуда: неизвестныеМетки(свод),
    безФиналов: !все.some(у => у.вид === "финал"),
  };
}

/** Метки, которые где-то требуются, но ни один узел их не ставит. */
function неизвестныеМетки(свод) {
  const ставятся = new Set();
  for (const у of свод.узлы ?? []) for (const м of у.ставит ?? []) ставятся.add(м);
  const стоят = new Set(Object.entries(свод.ход?.метки ?? {}).filter(([, в]) => в).map(([к]) => к));

  const нужные = new Set();
  for (const р of свод.рёбра ?? []) for (const м of р.нужны ?? []) нужные.add(м);

  return [...нужные].filter(м => !ставятся.has(м) && !стоят.has(м));
}

/* ─────────────────────────── раскладка ─────────────────────────── */

/**
 * Разложить узлы по слоям: слой — расстояние от начала в стрелках.
 *
 * Нужна, когда координат ещё нет: сценарий, написанный списком, должен
 * открыться читаемой картинкой, а не кучей карточек в одной точке.
 */
export function слои(свод) {
  const рёбра = свод.рёбра ?? [];
  const все = (свод.узлы ?? []).map(у => у.id);
  const слой = new Map();

  /*
   * Запас раскладывается отдельной полосой под сценарием: он не на пути,
   * и в столбцах от начала ему не место. Что за ним — идёт слоями от него.
   */
  const запас = new Set(запасы(свод));
  const очередь = [];
  if (свод.начало && все.includes(свод.начало)) { слой.set(свод.начало, 0); очередь.push(свод.начало); }

  const пройти = () => {
    for (let и = 0; и < очередь.length; и++) {
      const узел = очередь[и];
      for (const р of рёбра) {
        if (р.из !== узел || слой.has(р.в) || запас.has(р.в)) continue;
        слой.set(р.в, слой.get(узел) + 1);
        очередь.push(р.в);
      }
    }
  };
  пройти();
  // От запаса — тоже слоями, но начиная с первого: сам запас стоит в своей полосе.
  for (const id of запас) { слой.set(id, 0); очередь.push(id); }
  пройти();

  // Оставшиеся — те, до кого не дойти ни от начала, ни от запаса — становятся отдельным слоем справа.
  const хвост = Math.max(-1, ...слой.values()) + 1;
  for (const id of все) if (!слой.has(id)) слой.set(id, хвост);

  const поСлоям = new Map();
  for (const id of все) {
    if (запас.has(id)) continue;
    const с = слой.get(id);
    if (!поСлоям.has(с)) поСлоям.set(с, []);
    поСлоям.get(с).push(id);
  }

  const места = {};
  let строк = 0;
  for (const [с, узлы] of поСлоям) {
    узлы.forEach((id, и) => {
      места[id] = { x: 60 + с * 260, y: 60 + и * 150 };
    });
    строк = Math.max(строк, узлы.length);
  }
  [...запас].forEach((id, и) => {
    места[id] = { x: 60 + и * 260, y: 60 + строк * 150 + 60 };
  });
  return места;
}
